"""Builds an atom-consistent multi-frame trajectory from a heterogeneous ensemble.

This is what unblocks TRUE mdpocket ensemble mode. mdpocket requires every
frame to have identical atom count and ordering (it was designed for MD
trajectories). Independently solved crystal structures do not satisfy that:
they differ in resolved residues, altlocs, hydrogens, crystallographic
waters, and bound heteroatoms.

Strategy (lossy but explicit and verifiable):
  1. Take chain A protein atoms only; drop HETATM (ligands, waters, ions) so
     the cavity is defined by protein geometry alone -- never by a bound
     ligand's own volume.
  2. Drop altloc duplicates, keeping altloc ' ' or 'A'.
  3. Intersect on (resid, resname, atom_name) across all frames, so every
     frame contributes exactly the same atom set in the same order.
  4. Superpose all frames onto frame 0 (Kabsch on the common atoms).
  5. Emit a single multi-MODEL PDB that mdpocket can consume.

Residues dropped by the intersection are reported, because they define the
part of the protein this analysis is blind to.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from tools.structural_analysis import align_kabsch

BACKBONE_AND_SIDECHAIN = None  # keep all heavy atoms


@dataclass
class Atom:
    resid: int
    resname: str
    name: str
    element: str
    xyz: np.ndarray


@dataclass
class TrajectoryResult:
    path: Path
    n_frames: int
    n_atoms_per_frame: int
    frame_ids: list[str]
    common_residues: list[int]
    dropped_residues_per_frame: dict[str, list[int]] = field(default_factory=dict)
    rmsd_to_first: list[float] = field(default_factory=list)


def parse_protein_atoms(pdb_path: Path, chain: str = "A") -> list[Atom]:
    """Chain-A protein heavy atoms, no HETATM, no hydrogens, altloc-deduplicated."""
    atoms: list[Atom] = []
    seen: set[tuple[int, str]] = set()
    for line in Path(pdb_path).read_text().splitlines():
        if not line.startswith("ATOM"):
            continue
        if line[21] != chain:
            continue
        altloc = line[16]
        if altloc not in (" ", "A"):
            continue
        element = line[76:78].strip() or line[12:16].strip()[0]
        if element == "H":
            continue
        name = line[12:16].strip()
        try:
            resid = int(line[22:26])
        except ValueError:
            continue
        key = (resid, name)
        if key in seen:
            continue
        seen.add(key)
        atoms.append(Atom(resid=resid, resname=line[17:20].strip(), name=name,
                          element=element,
                          xyz=np.array([float(line[30:38]), float(line[38:46]),
                                        float(line[46:54])])))
    return atoms


def build_trajectory(pdb_paths: list[Path], out_path: Path,
                     chain: str = "A") -> TrajectoryResult:
    frames = {Path(p).stem: parse_protein_atoms(p, chain) for p in pdb_paths}
    if any(len(a) == 0 for a in frames.values()):
        empty = [k for k, v in frames.items() if not v]
        raise RuntimeError(f"No chain-{chain} protein atoms parsed for: {empty}")

    # Intersect on (resid, resname, atom_name) so ordering is well defined.
    keysets = [{(a.resid, a.resname, a.name) for a in atoms} for atoms in frames.values()]
    common = set.intersection(*keysets)
    if len(common) < 100:
        raise RuntimeError(f"Only {len(common)} common atoms across frames; "
                           "ensemble is too heterogeneous for mdpocket")
    ordered = sorted(common, key=lambda k: (k[0], k[2]))

    frame_ids = list(frames)
    coord_stack, dropped = [], {}
    for fid in frame_ids:
        lookup = {(a.resid, a.resname, a.name): a for a in frames[fid]}
        coord_stack.append(np.array([lookup[k].xyz for k in ordered]))
        all_res = {a.resid for a in frames[fid]}
        common_res = {k[0] for k in ordered}
        dropped[fid] = sorted(all_res - common_res)
    coords = np.stack(coord_stack)

    # Superpose onto frame 0.
    ref = coords[0] - coords[0].mean(axis=0)
    aligned = [ref]
    rmsds = [0.0]
    for i in range(1, len(coords)):
        mobile = coords[i] - coords[i].mean(axis=0)
        R, _ = align_kabsch(mobile, ref)
        rot = mobile @ R.T
        aligned.append(rot)
        rmsds.append(float(np.sqrt(((rot - ref) ** 2).sum(axis=1).mean())))

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as fh:
        fh.write("REMARK  Generated by ConforM-Agent tools/trajectory_builder.py\n")
        fh.write("REMARK  Atom-consistent multi-frame ensemble for mdpocket.\n")
        fh.write(f"REMARK  Frames: {', '.join(frame_ids)}\n")
        fh.write("REMARK  HETATM (ligands/waters/ions) removed; protein heavy atoms only.\n")
        for model_idx, (fid, xyz) in enumerate(zip(frame_ids, aligned), start=1):
            fh.write(f"MODEL     {model_idx:4d}\n")
            for serial, (key, pos) in enumerate(zip(ordered, xyz), start=1):
                resid, resname, name = key
                aname = f" {name:<3s}" if len(name) < 4 else name
                fh.write(
                    f"ATOM  {serial:5d} {aname:<4s} {resname:>3s} {chain}{resid:4d}    "
                    f"{pos[0]:8.3f}{pos[1]:8.3f}{pos[2]:8.3f}  1.00  0.00"
                    f"          {key[2][0]:>2s}\n")
            fh.write("ENDMDL\n")
        fh.write("END\n")

    return TrajectoryResult(
        path=out_path, n_frames=len(frame_ids), n_atoms_per_frame=len(ordered),
        frame_ids=frame_ids, common_residues=sorted({k[0] for k in ordered}),
        dropped_residues_per_frame=dropped, rmsd_to_first=rmsds,
    )


if __name__ == "__main__":
    import sys

    r = build_trajectory([Path(p) for p in sys.argv[1:-1]], Path(sys.argv[-1]))
    print(f"frames={r.n_frames} atoms/frame={r.n_atoms_per_frame} "
          f"residues={len(r.common_residues)}")
    print(f"RMSD to frame 0: {[round(x,2) for x in r.rmsd_to_first]}")
    for fid, dr in r.dropped_residues_per_frame.items():
        if dr:
            print(f"  {fid}: dropped {len(dr)} residues {dr[:12]}{'...' if len(dr)>12 else ''}")
    print(f"wrote {r.path}")
